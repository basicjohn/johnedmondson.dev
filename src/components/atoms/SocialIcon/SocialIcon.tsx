function iconKey(label: string): string {
  const l = label.toLowerCase();
  if (l.includes("github")) return "github";
  if (l.includes("linkedin")) return "linkedin";
  if (l.includes("twitter") || l === "x") return "x";
  if (l.includes("substack") || l.includes("newsletter")) return "substack";
  if (l.includes("pinterest")) return "pinterest";
  return "link";
}

